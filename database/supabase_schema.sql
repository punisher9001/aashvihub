-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.settings (
  k VARCHAR(100) PRIMARY KEY,
  v TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.delivery_zones (
  zone_key VARCHAR(50) PRIMARY KEY,
  label VARCHAR(100) NOT NULL,
  min_days INT NOT NULL,
  max_days INT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.themes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  theme_key VARCHAR(50) UNIQUE NOT NULL,
  name VARCHAR(150) NOT NULL,
  start_date DATE,
  end_date DATE
);

CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  icon VARCHAR(50) DEFAULT '',
  sort_order INT DEFAULT 0,
  is_available BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.subcategories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  image TEXT DEFAULT '',
  is_available BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcategory_id BIGINT REFERENCES public.subcategories(id) ON DELETE CASCADE,
  name VARCHAR(250) NOT NULL,
  description TEXT DEFAULT '',
  details TEXT DEFAULT '',
  image TEXT DEFAULT '',
  mrp NUMERIC(10,2) DEFAULT 0,
  price NUMERIC(10,2) NOT NULL,
  unit VARCHAR(100) DEFAULT '',
  stock INT DEFAULT 0,
  is_available BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.offers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) UNIQUE NOT NULL,
  description TEXT DEFAULT '',
  discount_percent NUMERIC(5,2) DEFAULT 0,
  min_order NUMERIC(10,2) DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  name VARCHAR(150) DEFAULT 'Dr Mukul Kumar',
  phone VARCHAR(20) DEFAULT '8988227729'
);

CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(150) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  address TEXT NOT NULL,
  pincode VARCHAR(10) NOT NULL,
  subtotal NUMERIC(10,2) NOT NULL,
  discount NUMERIC(10,2) DEFAULT 0,
  delivery_fee NUMERIC(10,2) DEFAULT 0,
  total NUMERIC(10,2) NOT NULL,
  coupon VARCHAR(50),
  payment_method VARCHAR(20) DEFAULT 'COD',
  payment_status VARCHAR(20) DEFAULT 'Pending',
  razorpay_order_id VARCHAR(100),
  razorpay_payment_id VARCHAR(100),
  status VARCHAR(50) DEFAULT 'Placed',
  order_status VARCHAR(50) DEFAULT 'Placed',
  delivery_pin VARCHAR(10) DEFAULT LPAD(FLOOR(RANDOM() * 9000 + 1000)::TEXT, 4, '0'),
  eta_text VARCHAR(100) DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

